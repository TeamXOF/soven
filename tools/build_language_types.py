"""Generate frontend/backend language types from the shared registry."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    data = json.loads((ROOT / 'shared/languages.json').read_text(encoding='utf-8'))
    codes = [row['code'] for row in data['languages']]
    enabled = [row['code'] for row in data['languages'] if row['enabled_for_reading']]
    if len(codes) != len(set(codes)) or len(codes) < data['target_minimum_languages']:
        raise ValueError('Language inventory must contain unique codes and cover the target')
    if not enabled:
        raise ValueError('At least one implemented reading language is required')
    union = lambda values: ' | '.join(json.dumps(code) for code in values)
    ts = '// Generated by tools/build_language_types.py; edit shared/languages.json first.\n'
    ts += f'export type LanguageCode = {union(codes)};\n'
    ts += f'export type ReadingLanguage = {union(enabled)};\n'
    ts += 'export const READING_LANGUAGES: readonly ReadingLanguage[] = ' + json.dumps(enabled) + ';\n'
    py = '# Generated by tools/build_language_types.py; edit shared/languages.json first.\nfrom typing import Literal\n\n'
    py += 'LanguageCode = Literal[' + ', '.join(json.dumps(code) for code in codes) + ']\n'
    py += 'ReadingLanguage = Literal[' + ', '.join(json.dumps(code) for code in enabled) + ']\n'
    return {ROOT / 'frontend/lib/language-types.ts': ts, ROOT / 'backend/core/language_types.py': py}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode('utf-8'))
    if stale:
        raise SystemExit('Generated language types are stale: ' + ', '.join(stale))
    print('Language type generation check passed' if args.check else 'Language types generated')


if __name__ == '__main__':
    main()
